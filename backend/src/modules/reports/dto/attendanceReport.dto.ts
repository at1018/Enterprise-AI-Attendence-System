import { z } from 'zod';

/**
 * DTO for creating an attendance report
 */
export const createAttendanceReportSchema = z.object({
  reportId: z.string().min(1, 'Report ID is required'),
  reportType: z.enum(['STUDENT_ATTENDANCE', 'CLASS_ATTENDANCE', 'TEACHER_ATTENDANCE', 'DAILY_SUMMARY', 'MONTHLY_SUMMARY', 'CUSTOM']),
  title: z.string().min(1, 'Title is required').max(200),
  description: z.string().max(500).optional(),
  generatedBy: z.string().min(1, 'Generated by is required'),
  startDate: z.coerce.date(),
  endDate: z.coerce.date(),
  filters: z.any().optional(),
  parameters: z.any().optional(),
  tenantId: z.string().min(1, 'Tenant ID is required')
});

export type CreateAttendanceReportDto = z.infer<typeof createAttendanceReportSchema>;